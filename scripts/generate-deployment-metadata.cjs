/* Generate read-only UI metadata from the existing full deployment descriptors. */
/* eslint-disable @typescript-eslint/no-var-requires */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const prettier = require('prettier');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const output = path.join(
  root,
  'source/utils/smartAccount/deploymentMetadata.ts'
);

function evaluate(relativePath, load) {
  const filename = path.join(root, relativePath);
  const { outputText } = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  });
  const module = { exports: {} };
  vm.runInNewContext(
    outputText,
    { module, exports: module.exports, require: load },
    { filename }
  );
  return module.exports;
}

async function main() {
  if (process.argv.slice(2).some((argument) => argument !== '--check'))
    throw new Error(
      'Usage: node scripts/generate-deployment-metadata.cjs [--check]'
    );
  const compat = evaluate('source/utils/ethersV6Compat.ts', require);
  const deployment = evaluate(
    'source/utils/smartAccount/deployment.ts',
    (name) => {
      if (name !== 'utils/ethersV6Compat')
        throw new Error(`Unexpected deployment dependency: ${name}`);
      return compat;
    }
  );
  const metadata = deployment.PALI_INFRASTRUCTURE_CONTRACTS.map(
    ({ deployCalldata, ...fields }) => {
      void deployCalldata;
      return fields;
    }
  );
  const constants = [
    'PALI_CREATE2_DEPLOYER_ADDRESS',
    'PALI_CANONICAL_ENTRYPOINT_ADDRESS',
    'PALI_CREATE2_DEPLOYER_MIN_RUNTIME_BYTE_LENGTH',
    'PALI_INFRASTRUCTURE_VERSION',
    'PALI_MULTICALL3_CANONICAL_ADDRESS',
    'PALI_CANONICAL_FACTORY_ADDRESS',
  ];
  const source = `// Generated by node scripts/generate-deployment-metadata.cjs.
// Full deployment.ts remains the source of truth; --check refuses stale metadata.
import type { PaliAuthenticatorModuleId } from './contracts';
import type { PaliInfrastructureContract, PaliInfrastructureContractId } from './deployment';
export type { PaliInfrastructureContract, PaliInfrastructureContractId } from './deployment';

export type PaliInfrastructureMetadata = Omit<PaliInfrastructureContract, 'deployCalldata'>;
${constants
  .map((key) => `export const ${key} = ${JSON.stringify(deployment[key])};`)
  .join('\n')}
export const PALI_INFRASTRUCTURE_METADATA: PaliInfrastructureMetadata[] = ${JSON.stringify(
    metadata
  )};
export const PALI_INFRASTRUCTURE_METADATA_BY_ID = Object.fromEntries(
  PALI_INFRASTRUCTURE_METADATA.map((contract) => [contract.id, contract])
) as Record<PaliInfrastructureContractId, PaliInfrastructureMetadata>;
export const PALI_MODULE_CANONICAL_ADDRESSES: Partial<Record<PaliAuthenticatorModuleId, string>> = ${JSON.stringify(
    deployment.PALI_MODULE_CANONICAL_ADDRESSES
  )};
export const ZKSYS_GAS_TANK_ADDRESSES: Partial<Record<number, string>> = ${JSON.stringify(
    deployment.ZKSYS_GAS_TANK_ADDRESSES
  )};

export const getPaliCanonicalEntryPointAddress = (
  // eslint-disable-next-line no-unused-vars, @typescript-eslint/no-unused-vars
  chainId?: number
): string => PALI_INFRASTRUCTURE_METADATA_BY_ID.entryPoint.address;
export const getPaliCanonicalFactoryAddress = (
  // eslint-disable-next-line no-unused-vars, @typescript-eslint/no-unused-vars
  chainId?: number
): string => PALI_INFRASTRUCTURE_METADATA_BY_ID.factory.address;
export const getZkSysGasTankAddress = (chainId?: number): string | undefined =>
  chainId === undefined ? undefined : ZKSYS_GAS_TANK_ADDRESSES[chainId];
`;
  const rendered = await prettier.format(source, {
    ...(await prettier.resolveConfig(output)),
    filepath: output,
  });
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== rendered)
      throw new Error(
        'Deployment metadata drift; run node scripts/generate-deployment-metadata.cjs'
      );
    console.log('Deployment metadata matches every computed descriptor.');
    return;
  }
  fs.writeFileSync(output, rendered);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
